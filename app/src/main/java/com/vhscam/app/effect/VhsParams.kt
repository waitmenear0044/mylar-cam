package com.vhscam.app.effect

/**
 * Параметры режима «VHS»: домашнее видео с камкордера 90-х (симуляция аналогового сигнала по мотивам
 * ntsc-rs). Все размеры и сдвиги — в долях полного кадра 3:4 (ширины/высоты итогового портретного кадра),
 * поэтому превью, видео и фото любого разрешения выглядят одинаково. Все «горизонтальные» артефакты
 * идут вдоль горизонтали итогового кадра, а не сенсора.
 */
data class VhsParams(
    val enabled: Boolean = true,
    /** Общая сила режима 0..1: ведёт все ползунки от нейтральных значений к текущим. */
    val strength: Float = 1f,

    // Сигнал
    /** Число строк по высоте кадра (176–720: нижний край — для «кнопочного телефона»). */
    val lines: Int = 480,
    /** Чёткость яркости 0..1: горизонтальный lowpass яркости (0 — сильно размыто). */
    val lumaSharpness: Float = 0.45f,
    /** Размытие цвета 0..1: цвет размазан по горизонтали намного сильнее яркости. */
    val chromaBlur: Float = 0.6f,
    /** Сдвиг цвета 0..1: цвет смещён вправо, плюс усреднение цвета между соседними строками. */
    val chromaShift: Float = 0.4f,

    // Края
    /** Звон 0..1: светлые ореолы у контуров (подчёркивание резкости с перерегулированием). */
    val ringing: Float = 0.35f,
    /** Видимость строк 0..1. */
    val scanlines: Float = 0.15f,
    /** Чересстрочность 0..1: гребёнка на движении (чётные/нечётные строки из разных кадров). */
    val interlace: Float = 0.3f,

    // Цвет
    /** Насыщенность 0..1.5 (1 = как у камеры). */
    val saturation: Float = 0.65f,
    /** Выцветшие чёрные 0..1. */
    val fadedBlacks: Float = 0.25f,
    /** −1 = зелёный, +1 = тёплый. */
    val tint: Float = 0.15f,
    /** −1 = плоско, +1 = контрастно. */
    val contrast: Float = 0.1f,

    // Лента
    /** Шум ленты 0..1: горизонтальные полоски (своя у каждой строки) и цветные пятна. */
    val tapeNoise: Float = 0.3f,
    /** Дрожание строк 0..1: медленное «плавание» строк по горизонтали и редкие всплески. */
    val jitter: Float = 0.3f,
    /** Головки 0..1: сбитые строки и шум внизу кадра (переключение головок). */
    val headSwitch: Float = 0.5f,
    /** Трекинг 0..1: редкая бегущая полоса искажений. */
    val tracking: Float = 0.1f,

    // Дефекты
    /** Дропауты 0..1: короткие светлые горизонтальные чёрточки. */
    val dropouts: Float = 0.25f,
    /** Смаз/шлейф 0..1: подмешивание предыдущего кадра, сильнее в тёмных местах. */
    val trail: Float = 0.6f,
    /** Свечение 0..1: пересвеченные места светятся и размазываются по горизонтали. */
    val bloom: Float = 0.35f,
    /** Блочность 0..1: квадратные блоки сжатия, как у видео с кнопочного телефона. */
    val blockiness: Float = 0f,

    // ЭЛТ (экран кинескопа): всё по умолчанию выключено — старые пресеты не меняются
    /** Маска люминофора 0..1 (сила). */
    val crtMask: Float = 0f,
    /** Тип маски: 0 — нет, 1 — RGB-точки, 2 — апертурная решётка, 3 — щелевая маска. */
    val crtMaskType: Int = 2,
    /** Размер ячейки маски (тройки RGB), доля короткой стороны кадра. */
    val crtMaskSize: Float = 0.006f,
    /** Кривизна экрана 0..1: бочка, скруглённые углы, тёмная рамка и виньетка. */
    val crtCurve: Float = 0f,
    /** Цветные облака 0..1: растянутые по горизонтали пастельные пятна цвета. */
    val crtClouds: Float = 0f,
    /** Скорость дрейфа облаков 0..1. */
    val crtCloudSpeed: Float = 0.3f,
    /** Муар/волна 0..1: волнистое искажение геометрии, сильнее к краю. */
    val crtWave: Float = 0f,

    // Оверлей
    /** «● REC» с мигающей точкой. */
    val showRec: Boolean = false,
    /** Угол «REC»: 0 — справа внизу, 1 — слева внизу, 2 — справа вверху, 3 — слева вверху. Дата — общий штамп. */
    val recCorner: Int = 3,

    /** Цифровой шум (по умолчанию выключен). */
    val noise: NoiseParams = NoiseParams(),
) {
    val hasOverlay: Boolean get() = showRec

    companion object {
        const val MIN_CRT_CELL = 0.002f
        const val MAX_CRT_CELL = 0.02f
        const val MIN_LINES = 176
        const val MAX_LINES = 720
        const val MAX_CORNER = 3
    }
}
