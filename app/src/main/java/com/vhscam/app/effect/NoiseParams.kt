package com.vhscam.app.effect

/**
 * Цифровой шум (общий для режимов): жёсткий, как у дешёвой камеры на высоком ISO, в отличие от
 * мягкого плёночного зерна. По умолчанию выключен (силы = 0), поэтому старые настройки и пресеты
 * выглядят как раньше.
 */
data class NoiseParams(
    /** Яркостный шум 0..1. */
    val luma: Float = 0f,
    /** Цветной шум (низкочастотные цветные пятна + цветные точки) 0..1. */
    val chroma: Float = 0f,
    /** Крупность 0..1 (от ~0.1% до ~0.6% короткой стороны полного кадра). */
    val size: Float = 0.3f,
    /** Насколько шум сильнее в тенях 0..1. */
    val shadows: Float = 0.6f,
) {
    val active: Boolean get() = luma > 0f || chroma > 0f
}
