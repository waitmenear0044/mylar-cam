package com.vhscam.app.effect

/**
 * Параметры режима «Плёнка». Все размеры — в долях кадра (короткой стороны), поэтому превью,
 * видео и фото разного разрешения выглядят одинаково. Значения по умолчанию подобраны по
 * референсам из reference/look: холодные мягкие света, чуть пурпурные тени, приглушённый цвет.
 */
data class FilmParams(
    val enabled: Boolean = true,
    /** Общая сила режима 0..1: масштабирует все ползунки сразу. */
    val strength: Float = 1f,

    /** Сила расщепления цвета (хроматическая аберрация) 0..1. */
    val splitStrength: Float = 0.55f,
    /** 0 = равномерный сдвиг по горизонтали кадра, 1 = чисто радиальный (растёт к краям). */
    val radiality: Float = 0.5f,
    /** Число выборок спектра (4..16): больше — плавнее радуга в кайме. */
    val splitSamples: Int = 10,

    /** Сила плёночной цветопередачи (кривые, кроссовер, мягкое плечо) 0..1. */
    val filmColor: Float = 0.8f,
    /** S-образный контраст 0..1. */
    val contrast: Float = 0.35f,
    /** Выцветание: приподнятые чёрные и чуть притушенные белые 0..1. */
    val fade: Float = 0.25f,
    /** Насыщенность 0..1.5 (1 = как есть). */
    val saturation: Float = 0.8f,
    /** -1 = холодный, +1 = тёплый. */
    val temperature: Float = -0.2f,

    /** Красно-оранжевое свечение вокруг ярких мест 0..1. */
    val halation: Float = 0.35f,
    /** Сила зерна 0..1. */
    val grain: Float = 0.5f,
    /** Размер зерна 0..1 (от ~0.07% до ~0.3% короткой стороны кадра). */
    val grainSize: Float = 0.6f,
    /** Смаз при движении: доля предыдущего кадра 0..1. */
    val motionBlur: Float = 0.2f,
    /** Мягкость (сниженный микроконтраст) 0..1. */
    val softness: Float = 0.3f,

    /** Тонировка теней: оттенок 0..360° и сила 0..1 (по умолчанию выключена). */
    val shadowHue: Float = 180f,
    val shadowTone: Float = 0f,
    /** Тонировка светов: оттенок 0..360° и сила 0..1 (по умолчанию выключена). */
    val highlightHue: Float = 40f,
    val highlightTone: Float = 0f,

    /** Цифровой шум (по умолчанию выключен). */
    val noise: NoiseParams = NoiseParams(),
) {
    companion object {
        const val MIN_SAMPLES = 4
        const val MAX_SAMPLES = 16
    }
}
